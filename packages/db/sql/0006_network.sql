CREATE TABLE operator (
  id text PRIMARY KEY REFERENCES entity(id) ON UPDATE CASCADE,
  name_ko text NOT NULL,
  name_en text,
  name_full text,
  short_ko text,
  kind text NOT NULL,
  status text NOT NULL,
  merged_into_id text REFERENCES operator(id) ON UPDATE CASCADE,
  founded_value text,
  founded_precision text,
  founded_from date GENERATED ALWAYS AS (fuzzy_from(founded_value, founded_precision)) STORED,
  founded_to date GENERATED ALWAYS AS (fuzzy_to(founded_value, founded_precision)) STORED,
  ended_value text,
  ended_precision text,
  ended_from date GENERATED ALWAYS AS (fuzzy_from(ended_value, ended_precision)) STORED,
  ended_to date GENERATED ALWAYS AS (fuzzy_to(ended_value, ended_precision)) STORED,
  homepage text,
  checked_at date NOT NULL,
  provenance_note text,
  review_status text NOT NULL DEFAULT 'unverified',
  reviewed_at timestamptz,
  editor_note text,
  extra jsonb NOT NULL DEFAULT '{}'::jsonb,
  version integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES app_user(id),
  updated_by uuid REFERENCES app_user(id),
  last_changeset_id text REFERENCES changeset(id) ON UPDATE CASCADE,
  deleted_at timestamptz,
  deleted_by uuid REFERENCES app_user(id),
  delete_reason text,
  CONSTRAINT operator_id_chk CHECK (id ~ '^op-[a-z0-9]+(-{1,2}[a-z0-9]+)*$'),
  CONSTRAINT operator_name_ko_chk CHECK (name_ko <> ''),
  CONSTRAINT operator_kind_chk CHECK (kind IN ('national_corp', 'local_corp', 'private', 'government', 'other')),
  CONSTRAINT operator_status_chk CHECK (status IN ('active', 'merged', 'dissolved')),
  CONSTRAINT operator_founded_fuzzy_chk CHECK (fuzzy_valid(founded_value, founded_precision)),
  CONSTRAINT operator_founded_precision_chk CHECK (founded_precision IN ('day', 'month', 'half', 'year', 'unknown')),
  CONSTRAINT operator_ended_fuzzy_chk CHECK (fuzzy_valid(ended_value, ended_precision)),
  CONSTRAINT operator_ended_precision_chk CHECK (ended_precision IN ('day', 'month', 'half', 'year', 'unknown')),
  CONSTRAINT operator_review_status_chk CHECK (review_status IN ('verified', 'unverified', 'flagged'))
);

CREATE TABLE station (
  id text PRIMARY KEY REFERENCES entity(id) ON UPDATE CASCADE,
  name_ko text NOT NULL,
  name_en text,
  name_hanja text,
  name_full text,
  kind text NOT NULL DEFAULT 'station',
  region_code text REFERENCES ref_region(code),
  region_basis text,
  address text,
  geom geography(Point, 4326),
  coord_source text,
  coord_basis text,
  coord_query text,
  coord_same_as_id text REFERENCES station(id) ON UPDATE CASCADE,
  coord_note text,
  grade text,
  history_text text,
  intro_text text,
  merge_into_id text REFERENCES station(id) ON UPDATE CASCADE,
  own_status text,
  own_opened_value text,
  own_opened_precision text,
  own_opened_from date GENERATED ALWAYS AS (fuzzy_from(own_opened_value, own_opened_precision)) STORED,
  own_opened_to date GENERATED ALWAYS AS (fuzzy_to(own_opened_value, own_opened_precision)) STORED,
  own_closed_value text,
  own_closed_precision text,
  own_closed_from date GENERATED ALWAYS AS (fuzzy_from(own_closed_value, own_closed_precision)) STORED,
  own_closed_to date GENERATED ALWAYS AS (fuzzy_to(own_closed_value, own_closed_precision)) STORED,
  checked_at date NOT NULL,
  provenance_note text,
  review_status text NOT NULL DEFAULT 'unverified',
  reviewed_at timestamptz,
  editor_note text,
  extra jsonb NOT NULL DEFAULT '{}'::jsonb,
  version integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES app_user(id),
  updated_by uuid REFERENCES app_user(id),
  last_changeset_id text REFERENCES changeset(id) ON UPDATE CASCADE,
  deleted_at timestamptz,
  deleted_by uuid REFERENCES app_user(id),
  delete_reason text,
  CONSTRAINT station_id_chk CHECK (id ~ '^stn-[a-z0-9]+(-{1,2}[a-z0-9]+)*$'),
  CONSTRAINT station_name_ko_chk CHECK (name_ko <> ''),
  CONSTRAINT station_kind_chk CHECK (kind IN ('station', 'signal_box', 'junction', 'yard', 'depot', 'freight')),
  CONSTRAINT station_region_basis_chk CHECK (region_basis IN ('address', 'interpolated', 'manual')),
  CONSTRAINT station_coord_source_chk CHECK (coord_source IN ('official', 'manual', 'derived')),
  CONSTRAINT station_coord_basis_chk CHECK (coord_basis IN ('parcel', 'district', 'township', 'existing_station')),
  CONSTRAINT station_own_status_chk CHECK (own_status IN ('operating', 'suspended', 'under_construction', 'planned', 'abandoned', 'closed')),
  CONSTRAINT station_own_opened_fuzzy_chk CHECK (fuzzy_valid(own_opened_value, own_opened_precision)),
  CONSTRAINT station_own_opened_precision_chk CHECK (own_opened_precision IN ('day', 'month', 'half', 'year', 'unknown')),
  CONSTRAINT station_own_closed_fuzzy_chk CHECK (fuzzy_valid(own_closed_value, own_closed_precision)),
  CONSTRAINT station_own_closed_precision_chk CHECK (own_closed_precision IN ('day', 'month', 'half', 'year', 'unknown')),
  CONSTRAINT station_review_status_chk CHECK (review_status IN ('verified', 'unverified', 'flagged')),
  CONSTRAINT station_geom_source_chk CHECK ((geom IS NULL) = (coord_source IS NULL)),
  CONSTRAINT station_coord_basis_chk2 CHECK (coord_basis IS NULL OR coord_source = 'derived'),
  CONSTRAINT station_merge_self_chk CHECK (merge_into_id <> id),
  CONSTRAINT station_same_as_self_chk CHECK (coord_same_as_id <> id),
  CONSTRAINT station_geom_bbox_chk CHECK (geom IS NULL OR (ST_Y(geom::geometry) BETWEEN 33 AND 39 AND ST_X(geom::geometry) BETWEEN 124 AND 132))
);

CREATE INDEX station_geom_idx ON station USING gist (geom);
CREATE INDEX station_name_trgm_idx ON station USING gin (name_ko gin_trgm_ops);
CREATE INDEX station_region_idx ON station (region_code);

CREATE TABLE line (
  id text PRIMARY KEY REFERENCES entity(id) ON UPDATE CASCADE,
  name_ko text NOT NULL,
  name_en text,
  name_hanja text,
  name_full text,
  category text NOT NULL,
  rail_class text NOT NULL,
  is_wide_area boolean,
  wide_area_note text,
  passenger_service boolean NOT NULL DEFAULT true,
  line_role text,
  status text NOT NULL,
  owner text,
  start_station_id text REFERENCES station(id) ON UPDATE CASCADE,
  end_station_id text REFERENCES station(id) ON UPDATE CASCADE,
  length_km numeric(7,2) CHECK (length_km >= 0),
  opened_value text,
  opened_precision text,
  opened_from date GENERATED ALWAYS AS (fuzzy_from(opened_value, opened_precision)) STORED,
  opened_to date GENERATED ALWAYS AS (fuzzy_to(opened_value, opened_precision)) STORED,
  closed_value text,
  closed_precision text,
  closed_from date GENERATED ALWAYS AS (fuzzy_from(closed_value, closed_precision)) STORED,
  closed_to date GENERATED ALWAYS AS (fuzzy_to(closed_value, closed_precision)) STORED,
  track text,
  electrification text,
  gauge_mm integer CHECK (gauge_mm > 0),
  design_speed_kmh integer CHECK (design_speed_kmh > 0),
  color text CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
  description text,
  parent_line_id text REFERENCES line(id) ON UPDATE CASCADE,
  checked_at date NOT NULL,
  provenance_note text,
  review_status text NOT NULL DEFAULT 'unverified',
  reviewed_at timestamptz,
  editor_note text,
  extra jsonb NOT NULL DEFAULT '{}'::jsonb,
  version integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES app_user(id),
  updated_by uuid REFERENCES app_user(id),
  last_changeset_id text REFERENCES changeset(id) ON UPDATE CASCADE,
  deleted_at timestamptz,
  deleted_by uuid REFERENCES app_user(id),
  delete_reason text,
  CONSTRAINT line_id_chk CHECK (id ~ '^line-[a-z0-9]+(-{1,2}[a-z0-9]+)*$'),
  CONSTRAINT line_name_ko_chk CHECK (name_ko <> ''),
  CONSTRAINT line_category_chk CHECK (category IN ('high_speed', 'conventional', 'metro', 'light_rail', 'tram', 'monorail', 'maglev')),
  CONSTRAINT line_rail_class_chk CHECK (rail_class IN ('high_speed', 'conventional', 'urban')),
  CONSTRAINT line_line_role_chk CHECK (line_role IN ('depot_line', 'connecting_line', 'wye')),
  CONSTRAINT line_status_chk CHECK (status IN ('operating', 'suspended', 'under_construction', 'planned', 'abandoned', 'closed')),
  CONSTRAINT line_opened_fuzzy_chk CHECK (fuzzy_valid(opened_value, opened_precision)),
  CONSTRAINT line_opened_precision_chk CHECK (opened_precision IN ('day', 'month', 'half', 'year', 'unknown')),
  CONSTRAINT line_closed_fuzzy_chk CHECK (fuzzy_valid(closed_value, closed_precision)),
  CONSTRAINT line_closed_precision_chk CHECK (closed_precision IN ('day', 'month', 'half', 'year', 'unknown')),
  CONSTRAINT line_track_chk CHECK (track IN ('single', 'double', 'quadruple', 'sextuple', 'single_parallel', 'partial_double')),
  CONSTRAINT line_review_status_chk CHECK (review_status IN ('verified', 'unverified', 'flagged')),
  CONSTRAINT line_parent_self_chk CHECK (parent_line_id <> id)
);

CREATE INDEX line_name_trgm_idx ON line USING gin (name_ko gin_trgm_ops);

CREATE TABLE line_region (
  line_id text REFERENCES line(id) ON DELETE CASCADE ON UPDATE CASCADE,
  region_code text REFERENCES ref_region(code),
  PRIMARY KEY (line_id, region_code)
);

CREATE TABLE line_operator (
  line_id text REFERENCES line(id) ON DELETE CASCADE ON UPDATE CASCADE,
  operator_id text REFERENCES operator(id) ON UPDATE CASCADE,
  role text NOT NULL DEFAULT 'operator',
  ord integer NOT NULL DEFAULT 0,
  note text,
  PRIMARY KEY (line_id, operator_id, role)
);

CREATE TABLE line_osm_map (
  line_id text PRIMARY KEY REFERENCES line(id) ON DELETE CASCADE ON UPDATE CASCADE,
  relation_ids bigint[] NOT NULL DEFAULT '{}',
  way_names text[] NOT NULL DEFAULT '{}',
  bbox numeric[] CHECK (bbox IS NULL OR array_length(bbox, 1) = 4),
  priority integer NOT NULL DEFAULT 0,
  include_construction boolean NOT NULL DEFAULT true,
  note text
);

CREATE TABLE line_station (
  id text PRIMARY KEY REFERENCES entity(id) ON UPDATE CASCADE,
  line_id text NOT NULL REFERENCES line(id) ON UPDATE CASCADE,
  station_id text NOT NULL REFERENCES station(id) ON UPDATE CASCADE,
  seq integer NOT NULL CHECK (seq >= 1),
  branch text,
  km numeric(7,2),
  station_code text,
  order_confirmed boolean NOT NULL DEFAULT true,
  name_ko text,
  name_en text,
  operator_id text REFERENCES operator(id) ON UPDATE CASCADE,
  status text NOT NULL,
  opened_value text,
  opened_precision text,
  opened_from date GENERATED ALWAYS AS (fuzzy_from(opened_value, opened_precision)) STORED,
  opened_to date GENERATED ALWAYS AS (fuzzy_to(opened_value, opened_precision)) STORED,
  closed_value text,
  closed_precision text,
  closed_from date GENERATED ALWAYS AS (fuzzy_from(closed_value, closed_precision)) STORED,
  closed_to date GENERATED ALWAYS AS (fuzzy_to(closed_value, closed_precision)) STORED,
  geom geography(Point, 4326),
  note text,
  version integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES app_user(id),
  updated_by uuid REFERENCES app_user(id),
  last_changeset_id text REFERENCES changeset(id) ON UPDATE CASCADE,
  deleted_at timestamptz,
  deleted_by uuid REFERENCES app_user(id),
  delete_reason text,
  CONSTRAINT line_station_id_chk CHECK (id ~ '^ls-[a-z0-9]+(-{1,2}[a-z0-9]+)*$'),
  CONSTRAINT line_station_status_chk CHECK (status IN ('operating', 'suspended', 'under_construction', 'planned', 'abandoned', 'closed')),
  CONSTRAINT line_station_opened_fuzzy_chk CHECK (fuzzy_valid(opened_value, opened_precision)),
  CONSTRAINT line_station_opened_precision_chk CHECK (opened_precision IN ('day', 'month', 'half', 'year', 'unknown')),
  CONSTRAINT line_station_closed_fuzzy_chk CHECK (fuzzy_valid(closed_value, closed_precision)),
  CONSTRAINT line_station_closed_precision_chk CHECK (closed_precision IN ('day', 'month', 'half', 'year', 'unknown')),
  CONSTRAINT line_station_seq_uniq UNIQUE (line_id, seq) DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX line_station_station_idx ON line_station (station_id);
CREATE INDEX line_station_line_idx ON line_station (line_id, seq);
CREATE INDEX line_station_code_idx ON line_station (station_code);
